export const dictionaries: Record<Lang, Record<keyof Dict, string>> = { pt, en };
export type TKey = keyof Dict;

export function translate(
  lang: Lang,
  key: TKey,
  params?: Record<string, string | number>,
): string {
  let text = dictionaries[lang][key] ?? dictionaries.pt[key] ?? String(key);
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}
